export interface TopEntry {
  t: string;
  y: number;
  m: number;
  r: number;
  h: number;
}

/** Демо-записи витрины: детерминированный набор (в продакшене — реальные оценки пользователя) */
export function showEntries(cat: ShowCat): TopEntry[] {
  const ci = SHOW_CATS.findIndex(([k]) => k === cat);
  const all: TopEntry[] = [];
  NAMES[cat].split("|").forEach((t, i) => {
    for (let k = 0; k < 4; k++) {
      all.push({ t, y: SHOW_YEARS[(i * 3 + k * 2 + ci) % 7], m: ((i * 7 + k * 5 + ci * 3) % 12) + 1, r: 10 - ((i * 37 + k * 13 + ci * 11) % 25) / 10, h: (i * 53 + ci * 80) % 360 });
    }
  });
  return all;
}

/** Топ-4 за период: год обязателен, месяц 0 = весь год; дубликаты названий убираются */
export function topFor(cat: ShowCat, year: number, month: number): TopEntry[] {
  return showEntries(cat)
    .filter((x) => x.y === year && (!month || x.m === month))
    .sort((a, b) => b.r - a.r)
    .filter((x, i, a) => a.findIndex((z) => z.t === x.t) === i)
    .slice(0, 4);
}

/** Случайная пара «категория + период», у которой точно есть записи */
export function randomPeriod(rnd: () => number = Math.random) {
  const ci = Math.floor(rnd() * 4);
  const cat = SHOW_CATS[ci][0];
  const pool = showEntries(cat).map((x) => [x.y, x.m] as const);
  const [year, month] = pool[Math.floor(rnd() * pool.length)];
  return { cat, year, month };
}
